import type { Page } from '@playwright/test'
import { expect, stableCanvasShot, test, waitForViewport } from './fixtures.ts'

const bar = (page: Page) => page.locator('.atlas-tour')
const modules = (page: Page) => page.locator('.atlas-modules')

test('tours start only on request, step with Previous/Next/dots, and Exit restores the previous view', async ({ page }) => {
  await page.goto('/?atlas=liver&bview=back#/anatomy')
  await waitForViewport(page)
  await expect(bar(page)).toHaveCount(0)
  const before = page.url()
  await modules(page).getByRole('button', { name: 'Tour: Follow a breath of air' }).click()
  await expect(bar(page).locator('#atlas-tour-heading')).toHaveText('Nasal cavity')
  await expect(page.locator('.viewport-badge')).toContainText('conceptual route, not timed')
  await expect(bar(page)).toContainText('Conceptual route of air')
  // The address keeps the pre-tour view; tours are never stored.
  expect(page.url()).toBe(before)
  await bar(page).getByRole('button', { name: 'Next' }).click()
  await expect(bar(page).locator('#atlas-tour-heading')).toHaveText('Pharynx')
  await bar(page).getByRole('button', { name: 'Previous' }).click()
  await expect(bar(page).locator('#atlas-tour-heading')).toHaveText('Nasal cavity')
  await bar(page).getByRole('button', { name: 'Step 6: Alveoli: gas exchange' }).click()
  await expect(bar(page)).toContainText('simple diffusion')
  await expect(page.locator('.atlas-nav')).toContainText('Selection is paused during the tour')
  await bar(page).getByRole('button', { name: 'Open the gas-exchange close-up' }).click()
  const view = page.locator('[data-view="alveolus"]')
  await expect(view).toContainText('Gas exchange in an alveolus')
  await view.getByRole('button', { name: 'Step 3: Oxygen moves into the blood' }).click()
  await expect(view).toContainText('higher to lower partial pressure')
  await view.getByRole('button', { name: 'Close close-up' }).click()
  await bar(page).getByRole('button', { name: 'Exit tour' }).click()
  await expect(bar(page)).toHaveCount(0)
  await expect(page.locator('#atlas-structure-heading')).toHaveText('Liver')
  await expect(page.getByRole('button', { name: 'Back', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(page.url()).toBe(before)
})

test('the food tour separates the route from accessory-organ contributions', async ({ page }) => {
  await page.goto('/#/anatomy')
  await waitForViewport(page)
  await modules(page).getByRole('button', { name: 'Tour: Follow food through the digestive tract' }).click()
  await expect(bar(page)).toContainText('“Contribution” are secretions added to the tract')
  await expect(bar(page).locator('.tour-kind')).toHaveText('Route')
  await bar(page).getByRole('button', { name: 'Step 6: Contribution: bile from the liver and gallbladder' }).click()
  await expect(bar(page).locator('.tour-kind')).toHaveText('Contribution (not part of the route)')
  await expect(bar(page)).toContainText('Highlighted: Liver, Gallbladder, Bile ducts.')
  await expect(page.locator('.heart-label', { hasText: 'Step 6 · Liver' })).toBeVisible()
  await bar(page).getByText('All steps as text').click()
  await expect(bar(page).locator('details ol li')).toHaveCount(9)
  await bar(page).getByRole('button', { name: 'Step 9: Large intestine' }).click()
  await bar(page).getByRole('button', { name: 'Finish tour' }).click()
  await expect(bar(page)).toHaveCount(0)
})

test('the nerve tour marks central vs peripheral; brain regions and nerve groups are selectable', async ({ page }) => {
  await page.goto('/#/anatomy')
  await waitForViewport(page)
  await modules(page).getByRole('button', { name: 'Tour: From a touch to a movement' }).click()
  await expect(bar(page)).toContainText('Peripheral nervous system')
  await bar(page).getByRole('button', { name: 'Step 4: Integration in the brain' }).click()
  await expect(bar(page)).toContainText('Central nervous system')
  await bar(page).getByRole('button', { name: 'Exit tour' }).click()
  const search = page.getByRole('searchbox', { name: 'Search body structures' })
  await search.fill('cerebellum')
  await page.locator('.atlas-nav').getByRole('button', { name: /^Cerebellum/ }).click()
  await expect(page.locator('.info')).toContainText('posterior surface of the brain stem')
  await search.fill('spinal nerves')
  await page.locator('.atlas-nav').getByRole('button', { name: /^Spinal nerves/ }).click()
  await expect(page.locator('.info')).toContainText('8 cervical, 12 thoracic, 5 lumbar, 5 sacral and 1 coccygeal')
})

test('the urine tour and nephron close-up; the circulation tour connects to the heart module', async ({ page }) => {
  // Still markers, so the canvas settles for comparison.
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#/anatomy')
  await waitForViewport(page)
  await modules(page).getByRole('button', { name: 'Tour: Follow urine from kidney to exit' }).click()
  await bar(page).getByRole('button', { name: 'Open the nephron close-up' }).click()
  const view = page.locator('[data-view="nephron"]')
  await view.getByRole('button', { name: 'Next' }).click()
  await expect(view.locator('.tour-title')).toHaveText('Filtration')
  await view.getByRole('button', { name: 'Step 4: Modification: secretion' }).click()
  await expect(view).toContainText('urea, potassium ions, ammonia, creatinine')
  await expect(view).toContainText('broad sequence only')
  await view.getByRole('button', { name: 'Close close-up' }).click()
  await bar(page).getByRole('button', { name: 'Exit tour' }).click()

  await modules(page).getByRole('button', { name: 'Tour: The systemic circuit through the body' }).click()
  const start = await stableCanvasShot(page, true)
  await bar(page).getByRole('button', { name: 'Next' }).click()
  expect((await stableCanvasShot(page, true)).equals(start)).toBe(false)
  await bar(page).getByRole('button', { name: 'Step 7: Then to the lungs' }).click()
  await bar(page).getByRole('button', { name: 'Open the detailed heart explorer' }).click()
  await expect(page.getByRole('group', { name: 'Anatomy module' }).getByRole('button', { name: 'Heart (detailed)' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Start blood-flow tour' })).toBeVisible()
})

