import type { Page } from '@playwright/test'
import { expect, search, test, waitForViewport } from './fixtures.ts'

const panel = (page: Page) => page.locator('.activity')
const inPanel = (page: Page, name: string | RegExp) => panel(page).getByRole('button', { name })
const progress = (page: Page) => panel(page).locator('.activity-progress')
const status = (page: Page) => panel(page).locator('.activity-status')
const chip = (page: Page, atomId: string) => page.locator('.measure-panel .chip').filter({ hasText: new RegExp(`^\\d?${atomId}$`) })

async function start(page: Page) {
  await panel(page).locator('.activity-launch').click()
  await inPanel(page, 'Start activity').click()
}

test('Chemistry: from Home, measure the H–O–H angle, then exit back to the previous view', async ({ page }) => {
  await page.goto('/?molecule=benzene&view=space-filling#/home')
  await page.getByRole('link', { name: /Measure the H–O–H angle in water/ }).click()
  await expect(page).toHaveURL(/#\/chemistry$/)
  await waitForViewport(page)

  // The introduction lists every change, and nothing changes before Start.
  await expect(panel(page)).toContainText('Molecule → Water (now Benzene)')
  await expect(panel(page)).toContainText('Display → Ball and stick (now Space-filling)')
  await expect(page.locator('#molecule-heading')).toHaveText('Benzene')
  await inPanel(page, 'Start activity').click()
  await expect(page.locator('#molecule-heading')).toHaveText('Water')
  await expect(progress(page)).toHaveText('Step 1 of 3 · 0 of 3 done')
  await expect(status(page)).toHaveText('Waiting for: the Angle tool to be selected')

  // Steps are detected from real explorer state; the ordinary controls are used.
  await page.getByRole('button', { name: 'Angle', exact: true }).click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  await chip(page, 'O1').click() // wrong order: O is not the vertex
  await chip(page, 'H1').click()
  await chip(page, 'H2').click()
  await expect(status(page)).toContainText('Waiting for')
  await page.locator('.measure-panel').getByRole('button', { name: 'Clear' }).click()
  await chip(page, 'H1').click()
  await chip(page, 'O1').click()
  await chip(page, 'H2').click()
  await expect(page.locator('.measure-result')).toContainText('104.5°')
  await expect(status(page)).toHaveText('Done')

  // A reflection step is marked by the user, never by time.
  await inPanel(page, 'Next').click()
  await page.waitForTimeout(1500)
  await expect(progress(page)).toHaveText('Step 3 of 3 · 2 of 3 done')
  await inPanel(page, 'I’ve explored this').click()
  await inPanel(page, 'Finish').click()
  await expect(panel(page)).toContainText('Lone pairs repel more strongly than bonding pairs')
  await expect(panel(page)).toContainText('not a test of understanding')
  await expect(panel(page).getByRole('link', { name: /OpenStax Chemistry 2e/ })).toHaveAttribute('href', /openstax\.org/)

  // Activity progress never reaches the URL.
  expect(page.url()).not.toMatch(/activity|step/i)

  await inPanel(page, 'Exit and restore my view').click()
  await expect(page.locator('#molecule-heading')).toHaveText('Benzene')
  await expect(page.getByRole('button', { name: 'Space-filling' })).toHaveAttribute('aria-pressed', 'true')
  const q = await search(page)
  expect([q.get('molecule'), q.get('view')]).toEqual(['benzene', 'space-filling'])
  await expect(panel(page).locator('.activity-launch')).toBeVisible()
})

test('Physics: pauses playback before setup, detects both launches, and exits paused', async ({ page }) => {
  await page.goto('/?speed=15&angle=45&height=5&gravity=9.81#/physics')
  await waitForViewport(page)
  await page.getByRole('button', { name: 'Launch', exact: true }).click()
  await expect(page.locator('.status-tag')).toHaveText('In flight')
  await panel(page).locator('.activity-launch').click()
  await expect(panel(page)).toContainText('The flight that is playing is paused, then time resets to t = 0')
  await inPanel(page, 'Start activity').click()

  await expect(page.locator('.status-tag')).not.toHaveText('In flight')
  const q = await search(page)
  expect([q.get('speed'), q.get('angle'), q.get('height'), q.get('gravity')]).toEqual(['20', '30', '0', '9.81'])

  // Software WebGL renders slowly, and the frame-step cap slows simulated time with it; 2× keeps the test short.
  await page.getByRole('button', { name: 'Playback speed 2 times' }).click()
  await page.getByRole('button', { name: 'Launch', exact: true }).click()
  await expect(status(page)).toHaveText('Done', { timeout: 30_000 })
  await inPanel(page, 'Next').click()
  await page.getByRole('button', { name: 'Save as Run A' }).click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  const angle = page.getByRole('textbox', { name: /^Launch angle/ })
  await angle.fill('60')
  await angle.press('Enter')
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  await page.getByRole('button', { name: 'Launch', exact: true }).click()
  await expect(status(page)).toHaveText('Done', { timeout: 30_000 })
  await inPanel(page, 'Finish').click()
  // The explanation uses the app's own calculation: R = 20²·sin 60°/9.81 = 35.3 m for both.
  await expect(panel(page)).toContainText('both launches land 35.3 m away')

  // Start the 60° launch playing, then exit: the old configuration comes back paused.
  await page.getByRole('button', { name: 'Launch again' }).click()
  await expect(page.locator('.status-tag')).toHaveText('In flight')
  await inPanel(page, 'Exit and restore my view').click()
  const r = await search(page)
  expect([r.get('speed'), r.get('angle'), r.get('height')]).toEqual(['15', '45', '5'])
  await expect(page.getByRole('button', { name: 'Resume' })).toBeVisible()
  const t = await page.locator('.readout > div').filter({ hasText: 'Time t' }).locator('dd').textContent()
  await page.waitForTimeout(800)
  await expect(page.locator('.readout > div').filter({ hasText: 'Time t' }).locator('dd')).toHaveText(t!)
  await expect(page.getByRole('button', { name: 'Clear comparison' })).toHaveCount(0)
})

test('Mathematics: detects the y = constant section and the saddle point', async ({ page }) => {
  await page.goto('/?surface=sine&amp=1&k=1#/mathematics')
  await waitForViewport(page)
  await start(page)
  await expect(page.locator('#math-heading')).toContainText('Saddle')
  await expect(page.locator('.slice-graph .graph-title')).toContainText('Cross-section at x = 1.00')
  await inPanel(page, 'I’ve explored this').click()
  await inPanel(page, 'Next').click()
  await page.getByRole('button', { name: 'y = constant' }).click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  await inPanel(page, 'Next').click()
  for (const [label, value] of [[/^x/, '0'], [/^y/, '0']] as const) {
    const input = page.getByRole('textbox', { name: label })
    await input.fill(value)
    await input.press('Enter')
  }
  await expect(status(page)).toHaveText('Done')
  await expect(progress(page)).toHaveText('Step 4 of 4 · 3 of 4 done')
  await inPanel(page, 'Exit activity and restore your previous view').click()
  await expect(page.locator('#math-heading')).toContainText('Sinusoidal surface')
  expect((await search(page)).get('surface')).toBe('sine')
})

test('Biology: detects the Golgi, isolation and following its cargo to the rough ER', async ({ page }) => {
  await page.goto('/?structure=nucleus&cell=whole#/biology')
  await waitForViewport(page)
  const before = await search(page)
  await start(page)
  await expect(page.locator('#structure-heading')).toHaveCount(0)
  await page.locator('.structure-item', { hasText: 'Golgi apparatus' }).click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  await page.getByRole('button', { name: 'Isolate' }).click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  await page.getByRole('tab', { name: 'Structure & relationships' }).click()
  await page.locator('.relation-link', { hasText: 'Rough endoplasmic reticulum' }).click()
  await expect(status(page)).toHaveText('Done')
  await panel(page).getByRole('button', { name: 'Exit', exact: true }).click()
  await expect(page.locator('#structure-heading')).toHaveText('Nucleus')
  const q = await search(page)
  expect([q.get('structure'), q.get('cell')]).toEqual([before.get('structure'), before.get('cell')])
})

test('Anatomy: ends a running tour explicitly, uses the tour, and restores the pre-tour view', async ({ page }) => {
  await page.goto('/?part=aorta&heart=whole#/anatomy')
  await waitForViewport(page)
  await page.getByRole('button', { name: 'Start blood-flow tour' }).click()
  await panel(page).locator('.activity-launch').click()
  await expect(panel(page)).toContainText('Ends the blood-flow tour in progress')
  await inPanel(page, 'Start activity').click()
  await expect(page.locator('.tour-bar')).toHaveCount(0)

  await page.locator('.structure-item', { hasText: 'Right ventricle' }).first().click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  await page.locator('.structure-item', { hasText: 'Pulmonary valve' }).first().click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  await page.getByRole('button', { name: 'Start blood-flow tour' }).click()
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Next').click()
  const tourNext = page.locator('.tour-bar').getByRole('button', { name: 'Next' })
  for (let i = 0; i < 6; i++) await tourNext.click()
  await expect(page.locator('#tour-heading')).toContainText('Lungs')
  await expect(status(page)).toHaveText('Done')
  await inPanel(page, 'Finish').click()
  await expect(panel(page)).toContainText('pulmonary arteries carry oxygen-poor blood')

  await inPanel(page, 'Exit and restore my view').click()
  await expect(page.locator('.tour-bar')).toHaveCount(0)
  await expect(page.locator('#part-heading')).toHaveText('Aorta')
  const q = await search(page)
  expect([q.get('part'), q.get('heart')]).toEqual(['aorta', 'whole'])
})

