import type { Page } from '@playwright/test'
import { expect, stableCanvasShot, test, waitForViewport } from './fixtures.ts'

const heading = (page: Page) => page.locator('#atlas-structure-heading')
const params = (page: Page) => new URL(page.url()).searchParams

async function pick(page: Page, query: string, name: RegExp) {
  const box = page.getByRole('searchbox', { name: 'Search body structures' })
  await box.fill(query)
  await page.locator('.atlas-nav').getByRole('button', { name }).first().click()
  await box.fill('')
}

test('bones: detailed skeleton, groups explained, joints linked, pairs isolated together', async ({ page }) => {
  await page.goto('/?layers=skeletal#/anatomy')
  await waitForViewport(page)
  await pick(page, 'carpal', /^Left carpal bones/)
  await expect(page.locator('.info')).toContainText('Eight small bones')
  await expect(page.locator('.inline-note').first()).toContainText('drawn as one block')
  await pick(page, 'humerus', /^Left humerus/)
  await page.locator('.relation-list').getByRole('button', { name: 'Left elbow joint' }).click()
  await expect(heading(page)).toHaveText('Left elbow joint')
  await expect(page.locator('.info')).toContainText('uniaxial hinge joint')
  await pick(page, 'femur', /^Left femur/)
  await page.getByRole('button', { name: 'Isolate both sides' }).click()
  await expect(page.locator('.viewport-badge')).toContainText('Isolated: Left femur and the other side')
  await pick(page, 'vertebral', /^Vertebral column/)
  await expect(page.locator('.relation-list')).toContainText('Cervical vertebrae (C1–C7)')
})

test('muscles: individual vs grouped, attachments only where sourced, and the skeleton+muscle toggle', async ({ page }) => {
  await page.goto('/#/anatomy')
  await waitForViewport(page)
  const toggle = page.getByRole('button', { name: 'Skeleton and muscles together' })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('checkbox', { name: 'Muscular' })).toBeChecked()
  await toggle.click()
  await expect(page.getByRole('checkbox', { name: 'Skeletal' })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Muscular' })).not.toBeChecked()

  await pick(page, 'sternocleido', /^Left sternocleidomastoid/)
  const attach = page.locator('.info-section', { has: page.getByRole('heading', { name: 'Attachments' }) })
  await expect(attach).toContainText('Origin')
  await expect(attach).toContainText('Sternum; clavicle')
  await expect(attach.getByRole('link', { name: /11\.3 Axial Muscles/ })).toBeVisible()
  await pick(page, 'deltoid', /^Left deltoid/)
  await expect(attach).toContainText('Not listed')
  await pick(page, 'hamstring', /^Left hamstring group/)
  await expect(page.locator('.atlas-facts')).toContainText('Grouped representation')
  await expect(page.locator('.inline-note').first()).toContainText('biceps femoris, semitendinosus, semimembranosus')
})

test('elbow and knee flexion demonstrations: labelled, conceptual, manual and never in the link', async ({ page }) => {
  await page.goto('/#/anatomy')
  await waitForViewport(page)
  const panel = page.locator('.movement-panel')
  await panel.getByRole('button', { name: 'Elbow flexion' }).click()
  await expect(page.locator('.viewport-badge')).toContainText('Elbow flexion (left) · conceptual motion, not a measured range')
  await expect(panel).toContainText('Starts from the anatomical position')
  await expect(panel).toContainText('no angles are given')
  await expect(panel).toContainText('Flexor: Left biceps brachii')
  await expect(panel).toContainText('Opposes: Left triceps brachii')
  await expect(page.locator('.heart-label', { hasText: 'Flexor · biceps brachii' })).toBeVisible()
  const slider = panel.getByLabel('Flexion (conceptual)')
  await expect(slider).toHaveAttribute('aria-valuetext', 'Extended (reference posture)')
  const before = await stableCanvasShot(page, true)
  await slider.fill('80')
  await expect(slider).toHaveAttribute('aria-valuetext', 'Mostly flexed')
  await expect(panel.locator('.pose-sketch')).toHaveAttribute('aria-label', /mostly flexed\. Anterior is to the left/)
  expect((await stableCanvasShot(page, true)).equals(before)).toBe(false)
  expect([...params(page).keys()].some((k) => /demo|flex/.test(k))).toBe(false)

  await panel.getByRole('button', { name: 'Knee flexion' }).click()
  await panel.getByRole('button', { name: 'Right side' }).click()
  await expect(panel).toContainText('Flexor: Right hamstring group')
  await expect(panel.locator('.pose-sketch')).toHaveAttribute('aria-label', /from the body’s right.*Anterior is to the right/)
  await panel.getByRole('button', { name: 'Play' }).click()
  await expect.poll(async () => Number(await slider.inputValue())).toBeGreaterThan(5)
  await panel.getByRole('button', { name: 'Pause' }).click()
  await panel.getByRole('button', { name: 'Exit demonstration' }).click()
  await expect(page.locator('.viewport-badge')).not.toContainText('conceptual motion')
})

test('reduced motion: demonstrations have no Play button; the slider still works', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#/anatomy')
  await waitForViewport(page)
  const panel = page.locator('.movement-panel')
  await panel.getByRole('button', { name: 'Elbow flexion' }).click()
  await expect(panel.getByRole('button', { name: 'Play' })).toHaveCount(0)
  await panel.getByLabel('Flexion (conceptual)').fill('100')
  await expect(panel.locator('.movement-pose')).toHaveText('Flexed (end of this demonstration)')
})

test('the limb comparison is a readable table that selects structures', async ({ page }) => {
  await page.goto('/#/anatomy')
  await waitForViewport(page)
  await page.getByText('Compare upper and lower limbs').click()
  const table = page.locator('.limb-compare table')
  await expect(table.getByRole('row', { name: /Wrist \/ back of foot/ })).toContainText('8 carpals')
  await expect(table.getByRole('row', { name: /Wrist \/ back of foot/ })).toContainText('7 tarsals')
  await table.getByRole('button', { name: 'Show femur' }).click()
  await expect(heading(page)).toHaveText('Left femur')
})
