import type { Page } from '@playwright/test'
import { expect, test, waitForViewport } from './fixtures.ts'

const sectionButton = (page: Page, name: string) => page.getByRole('group', { name: 'Biology section' }).getByRole('button', { name })
const params = (page: Page) => new URL(page.url()).searchParams

test('bacterial cell: its own structures, representative vs variable features, and a three-way comparison', async ({ page }) => {
  await page.goto('/#/biology')
  await waitForViewport(page)
  await page.getByRole('group', { name: 'Cell type' }).getByRole('button', { name: 'Bacterium' }).click()
  expect(params(page).get('type')).toBe('bacterium')
  await expect(page.locator('.viewport-badge')).toContainText('Representative bacterial cell')
  const table = page.locator('.cell-compare table')
  await expect(table.getByRole('row', { name: /Cell wall/ })).toContainText('Yes (peptidoglycan in most)')
  await expect(table.getByRole('row', { name: /DNA/ })).toContainText('In the nucleoid (no membrane)')
  await expect(page.locator('.cell-compare')).toContainText('Variable')
  await page.locator('.structure-item', { hasText: 'Nucleoid' }).click()
  await expect(page.locator('#structure-heading')).toHaveText('Nucleoid')
  await expect(page.locator('.info')).toContainText('not enclosed by a membrane')
  await page.locator('.structure-item', { hasText: 'Flagellum' }).click()
  await expect(page.locator('.info')).toContainText('Some prokaryotes have flagella')
  await page.reload()
  await waitForViewport(page)
  await expect(page.locator('#structure-heading')).toHaveText('Flagellum')
  // A plant link made before the bacterium existed still opens the plant cell.
  await page.goto('/?structure=chloroplast&cell=cutaway&type=plant#/biology')
  await waitForViewport(page)
  await expect(page.locator('#structure-heading')).toHaveText('Chloroplasts')
})

test('DNA and RNA: inspect pairs, step through, and build RNA from the template', async ({ page }) => {
  await page.goto('/#/biology')
  await sectionButton(page, 'DNA and RNA').click()
  expect(params(page).get('bsec')).toBe('dna')
  const view = page.locator('.process-view')
  await view.getByRole('button', { name: '3: G–C' }).click()
  await expect(view.locator('.readout')).toContainText('3 hydrogen bonds')
  await expect(view.locator('.readout')).toContainText('guanine (purine)')
  await view.getByRole('button', { name: 'Step 3: Strand direction' }).click()
  await expect(view).toContainText('antiparallel')
  await view.getByRole('button', { name: 'Next' }).click()
  await expect(view.locator('.tour-title')).toHaveText('Transcription: making RNA')
  const add = view.getByRole('button', { name: 'Add the next RNA nucleotide' })
  for (let i = 0; i < 12; i++) await add.click()
  await expect(view).toContainText('Done: RNA 5′-AUGGCAUUCGAC-3′, the coding strand with U for T.')
  await expect(add).toBeDisabled()
})

test('cell division: manual stages, consistent chromatid terms, cytokinesis apart from mitosis, no gametes', async ({ page }) => {
  await page.goto('/?bsec=division#/biology')
  const view = page.locator('.process-view')
  await expect(view.locator('.tour-title')).toHaveText('Prophase')
  await expect(view).toContainText('4 chromosomes, each of 2 sister chromatids')
  await view.getByRole('button', { name: 'Step 5: Anaphase' }).click()
  await expect(view).toContainText('Each chromatid is now called a chromosome')
  await expect(view).toContainText('8 chromosomes in total')
  await view.getByRole('button', { name: 'Step 7: Cytokinesis (after mitosis)' }).click()
  await expect(view.locator('.stage-kind')).toHaveText('Not part of mitosis: cytokinesis divides the cytoplasm')
  await view.getByRole('button', { name: 'Step 1: Interphase (before mitosis)' }).click()
  await expect(view.locator('.stage-kind')).toHaveText('Not part of mitosis: interphase')
  await expect(page.locator('.info')).toContainText('it does not make gametes')
  await expect(view).toContainText('Illustrative cell with 4 chromosomes')
})

test('energy processes: net equations apart from stages, linked to the chloroplast and mitochondrion', async ({ page }) => {
  await page.goto('/?bsec=energy#/biology')
  const view = page.locator('.process-view')
  await expect(view.locator('.net-equation').first()).toContainText('Simplified net equation')
  await expect(view.locator('.net-equation').first()).toContainText('6CO₂ + 6H₂O → C₆H₁₂O₆ + 6O₂')
  await view.getByRole('button', { name: /Pyruvate oxidation and the citric acid cycle/ }).click()
  await expect(view).toContainText('Where: Matrix of the mitochondrion')
  await view.getByRole('button', { name: 'Show the mitochondrion in the animal cell' }).click()
  await waitForViewport(page)
  await expect(page.locator('#structure-heading')).toHaveText('Mitochondria')
  expect(params(page).get('bsec')).toBeNull()
  await page.goBack().catch(() => undefined)
})

test('biology sections save and reopen', async ({ page }) => {
  await page.goto('/?bsec=division#/biology')
  await page.getByRole('button', { name: 'Save exploration' }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.save-status')).toContainText('Cell division: mitosis')
  await page.goto('/')
  await page.locator('section', { has: page.getByRole('heading', { name: 'Saved explorations' }) }).getByRole('link', { name: /Cell division/ }).click()
  await expect(page.locator('.process-view .tour-title')).toHaveText('Prophase')
})
