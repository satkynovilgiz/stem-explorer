/* ---------- Geometry helpers ---------- */

/** The vertebral column's curve (posterior), top to bottom. */
const SPINE: Vec3[] = [
  [0, 8.85, -0.12],
  [0, 8.3, -0.2],
  [0, 7.6, -0.42],
  [0, 6.6, -0.48],
  [0, 5.6, -0.36],
  [0, 5.0, -0.32],
]

/** Point at fraction t (0 = top, 1 = bottom) along the spine polyline, by height. */
function spineAt(y: number): Vec3 {
  for (let i = 0; i < SPINE.length - 1; i++) {
    const [a, b] = [SPINE[i], SPINE[i + 1]]
    if (y <= a[1] && y >= b[1]) return lerp(a, b, (a[1] - y) / (a[1] - b[1]))
  }
  return y > SPINE[0][1] ? SPINE[0] : SPINE[SPINE.length - 1]
}

/** n vertebral bodies spaced evenly between two heights. */
function vertebrae(n: number, top: number, bottom: number, size: number): Shape[] {
  return Array.from({ length: n }, (_, i) => {
    const y = top - ((top - bottom) * (i + 0.5)) / n
    return { kind: 'box', center: spineAt(y), size: [size, ((top - bottom) / n) * 0.72, size * 0.85] } as Shape
  })
}

/** One rib (left side) at index 0–11. Ribs 1–7 reach the sternum; 11–12 are short. */
function rib(i: number): Shape {
  const y = 7.85 - i * 0.16
  const rx = 0.62 + Math.min(i, 7) * 0.07 - Math.max(0, i - 8) * 0.06
  const end = i < 7 ? Math.PI * 0.03 : i < 10 ? Math.PI * 0.12 : Math.PI * 0.55
  return { kind: 'tube', points: arc(0, y, -0.05, rx, 0.62, Math.PI, end, 8, 0.25), radius: 0.032 }
}

const capsule = (from: Vec3, to: Vec3, radius: number): Shape => ({ kind: 'capsule', from, to, radius })

